function lookup(path: string): Leaf | Dict | undefined {
  return path.split('.').reduce<Leaf | Dict | undefined>((node, key) => {
    if (node && typeof node === 'object') return (node as Dict)[key]
    return undefined
  }, strings)
}

/** Looks up a string by dot path (e.g. `t('nav.home')`); call-through for parameterized strings. */
export function t(path: string, ...args: (string | number)[]): string {
  const node = lookup(path)
  if (typeof node === 'function') return (node as (...a: (string | number)[]) => string)(...args)
  if (typeof node === 'string') return node
  throw new Error(`Missing i18n string: ${path}`)
}

export function categoryLabel(category: string): string {
  return (strings.categories as Record<string, string>)[category] ?? category
}

export function verdictLabel(verdict: string | null | undefined): string {
  if (!verdict) return t('common.unknown')
  return (strings.verdicts as Record<string, string>)[verdict] ?? verdict
}
